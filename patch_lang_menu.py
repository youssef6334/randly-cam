def main():
    if not os.path.isdir(PUBLIC):
        sys.exit("ERROR: run this from the project folder (the one that contains 'public').")
    print(("APPLY" if APPLY else "DRY-RUN") + " in " + os.path.abspath(PUBLIC))
    writes = []

    for name, text in (("lang-menu.css", CSS), ("lang-menu.js", JS)):
        p = os.path.join(PUBLIC, name)
        new = text.replace("\r\n", "\n").encode("utf-8")
        old = open(p, "rb").read().replace(b"\r\n", b"\n") if os.path.exists(p) else None
        if old == new:
            print("ok     " + name + ": up to date")
        else:
            writes.append((p, new)); print("CHANGE " + name + ("  (new file)" if old is None else "  (updated)"))

    header_rx = re.compile(rb'class="[^"]*\bapp-header\b')
    new_tag = ("/lang-menu.").encode()
    pages = homes = bumped = already = 0
    for f in sorted(glob.glob(os.path.join(PUBLIC, "*.html"))):
        base = os.path.basename(f)
        d = open(f, "rb").read()
        is_home = b'id="landingPage"' in d
        if b"lang-menu.js" in d:
            # already patched: only refresh the cache-buster version if it changed
            nd = OLD_TAG_RX.sub(lambda m: b"/lang-menu." + m.group(1) + b"?v=" + VERSION.encode(), d)
            if nd != d:
                writes.append((f, nd)); bumped += 1
            else:
                already += 1
            continue
        if not header_rx.search(d):
            print("NOTE   " + base + ": no site header, skipped"); continue
        if d.count(b"</head>") != 1 or d.count(b"</body>") != 1:
            print("NOTE   " + base + ": unexpected </head>/</body>, skipped"); continue
        nl = b"\r\n" if b"\r\n" in d else b"\n"
        nd = d.replace(b"</head>", CSS_TAG.encode() + nl + b"</head>")
        nd = nd.replace(b"</body>", JS_TAG.encode() + nl + b"</body>")
        writes.append((f, nd))
        if is_home: homes += 1
        else: pages += 1
    print(("CHANGE " if pages else "ok     ") + str(pages) + " content page(s): menu added (blog / articles / about / rules / privacy / terms)")
    print(("CHANGE " if homes else "ok     ") + str(homes) + " chat home page(s): landing menu added")
    if bumped: print("CHANGE " + str(bumped) + " page(s): version refreshed")
    if already: print("ok     " + str(already) + " page(s) already had the menu")

    if not writes:
        print("\nNothing to do."); return
    if not APPLY:
        print("\nLooks right? Run again with --apply"); return
    for f, d in writes:
        open(f, "wb").write(d)
    print("\nDone: " + str(len(writes)) + " file(s) written.")

main()